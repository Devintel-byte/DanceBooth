// Generates the bundled DEVELOPMENT routine manifest and a SYNTHETIC replay
// fixture for it. Both are placeholder content: the choreography is a simple
// procedural move list and the fixture is generated geometry, not a recording
// of a person. Run with: pnpm assets:dev-content
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { routineManifestSchema, replayFixtureSchema, type RoutineManifest, type SegmentName } from '@booth/contracts';
import { RoutinePoseSampler } from '@booth/choreography';
import { synthesizeLandmarks } from '@booth/scoring';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const assets = path.join(root, 'assets');

type P = Partial<Record<SegmentName, [number, number]>>;
const DOWN_L: P = { leftUpperArm: [0.2, -1], leftForearm: [0.1, -1] };
const DOWN_R: P = { rightUpperArm: [-0.2, -1], rightForearm: [-0.1, -1] };
const MOVES: Record<string, P> = {
  'Arms Up': { leftUpperArm: [0.35, 1], leftForearm: [0.15, 1], rightUpperArm: [-0.35, 1], rightForearm: [-0.15, 1] },
  'T Pose': { leftUpperArm: [1, 0], leftForearm: [1, 0], rightUpperArm: [-1, 0], rightForearm: [-1, 0] },
  'Point Left': { leftUpperArm: [1, 0.45], leftForearm: [1, 0.6], ...DOWN_R },
  'Point Right': { rightUpperArm: [-1, 0.45], rightForearm: [-1, 0.6], ...DOWN_L },
  Flex: { leftUpperArm: [1, 0], leftForearm: [0, 1], rightUpperArm: [-1, 0], rightForearm: [0, 1] },
  'Disco Left': { leftUpperArm: [0.55, 0.85], leftForearm: [0.45, 0.9], rightUpperArm: [0.25, -1], rightForearm: [0.35, -1] },
  'Disco Right': { rightUpperArm: [-0.55, 0.85], rightForearm: [-0.45, 0.9], leftUpperArm: [-0.25, -1], leftForearm: [-0.35, -1] },
  'Hands On Hips': { leftUpperArm: [0.6, -0.8], leftForearm: [-0.8, -0.35], rightUpperArm: [-0.6, -0.8], rightForearm: [0.8, -0.35] },
  'Lean Left': { torso: [0.25, 1], leftUpperArm: [1, 0.2], leftForearm: [1, 0.3], rightUpperArm: [-0.3, 1], rightForearm: [-0.1, 1] },
  'Lean Right': { torso: [-0.25, 1], rightUpperArm: [-1, 0.2], rightForearm: [-1, 0.3], leftUpperArm: [0.3, 1], leftForearm: [0.1, 1] },
};
const SEQUENCE = [
  'Arms Up', 'T Pose', 'Point Left', 'Point Right', 'Flex', 'Hands On Hips', 'Disco Left', 'Disco Right',
  'Lean Left', 'Lean Right', 'Arms Up', 'Flex', 'Point Left', 'Point Right', 'T Pose', 'Hands On Hips',
  'Disco Left', 'Disco Right', 'Disco Left', 'Disco Right', 'Lean Left', 'Lean Right', 'Flex', 'Arms Up',
  'Point Right', 'Point Left', 'Hands On Hips', 'T Pose', 'Arms Up',
];

const BPM = 120;
const audioFile = 'audio/dev-groove-120bpm.wav';
const audioHash = createHash('sha256').update(readFileSync(path.join(assets, audioFile))).digest('hex');

const routineDraft = {
  schemaVersion: 1,
  id: 'dev-groove',
  contentVersion: '0.1.0',
  title: 'Dev Groove',
  subtitle: 'DEVELOPMENT ROUTINE - placeholder content',
  audio: { file: audioFile, offsetMs: 0 },
  animation: { kind: 'procedural-keyframes' },
  durationSec: 32.5,
  bpm: BPM,
  firstBeatSec: 0,
  sections: [
    { name: 'Count-in', startSec: 0 },
    { name: 'Verse', startSec: 2 },
    { name: 'Chorus', startSec: 18 },
  ],
  difficulty: 'easy',
  mirroring: 'mirror',
  requiredGroups: ['arms', 'torso'],
  // One judged pose every two beats (1 s) after a 4-beat count-in.
  moves: SEQUENCE.map((label, i) => ({ timeSec: 2 + i, label, judged: true, pose: MOVES[label] })),
  license: {
    audio: {
      source: 'Synthesised by scripts/generate-dev-audio.mjs',
      license: 'Project-owned development asset',
      placeholder: true,
    },
    choreography: {
      source: 'Generated by scripts/generate-dev-content.ts',
      license: 'Project-owned development asset',
      placeholder: true,
    },
  },
  integrity: { [audioFile]: audioHash },
};

const routine: RoutineManifest = routineManifestSchema.parse(routineDraft);
mkdirSync(path.join(assets, 'routines'), { recursive: true });
writeFileSync(path.join(assets, 'routines', 'dev-groove.json'), JSON.stringify(routineDraft, null, 2) + '\n');

// Synthetic replay fixture: a "participant" performing the routine in mirror
// mode at 30 Hz, with small deterministic noise, a timing lag, and a 1.5 s
// occlusion of the left arm to exercise missing-joint handling.
function writeFixture(r: RoutineManifest, file = `${r.id}-synthetic.json`): number {
  let seed = 7;
  const noise = () => (((seed = (seed * 1103515245 + 12345) >>> 0) / 4294967296) - 0.5) * 0.006;
  const sampler = new RoutinePoseSampler(r);
  const frames = [];
  const HZ = 30;
  const LAG = 0.08;
  for (let i = 0; i <= r.durationSec * HZ; i++) {
    const t = i / HZ;
    const pose = sampler.sample(Math.max(0, t - LAG));
    const hidden = t > 12 && t < 13.5 ? (['leftElbow', 'leftWrist'] as const) : [];
    const lms = synthesizeLandmarks(pose, { mirroring: 'mirror', hipX: 0.5 + Math.sin(t * 0.7) * 0.03, hidden });
    frames.push({
      t: Number(t.toFixed(4)),
      bodies: [
        lms.map((l) => [
          Number((l.x + noise()).toFixed(5)),
          Number((l.y + noise()).toFixed(5)),
          0,
          Number((l.visibility ?? 1).toFixed(3)),
        ]),
      ],
    });
  }
  const fixture = replayFixtureSchema.parse({
    schemaVersion: 1,
    id: `${r.id}-synthetic`,
    provenance: {
      kind: 'synthetic',
      generator: 'scripts/generate-dev-content.ts (synthesizeLandmarks + RoutinePoseSampler)',
      createdAt: '2026-11-02',
      description:
        `Generated geometry performing ${r.id} in mirror mode with 80 ms lag, +/-0.3% jitter and a left-arm occlusion at 12-13.5 s. Not a recording of a person.`,
      routineId: r.id,
    },
    sourceWidth: 1280,
    sourceHeight: 720,
    frames,
  });
  mkdirSync(path.join(assets, 'fixtures'), { recursive: true });
  writeFileSync(path.join(assets, 'fixtures', file), JSON.stringify(fixture));
  return frames.length;
}

const frameCount = writeFixture(routine);
// Demo / replay mode (operator console "Use replay (demo)"): a synthetic dancer
// performing the event's default song, so the booth can be shown without a camera.
const profile = JSON.parse(readFileSync(path.join(assets, 'profiles', 'maltina.json'), 'utf-8')) as { enabledRoutines: string[] };
const demoFile = path.join(assets, 'routines', `${profile.enabledRoutines[0]}.json`);
if (existsSync(demoFile)) writeFixture(routineManifestSchema.parse(JSON.parse(readFileSync(demoFile, 'utf-8'))), 'demo-synthetic.json');
console.info(`wrote routine (${routine.moves.length} moves) and fixture (${frameCount} frames)`);
